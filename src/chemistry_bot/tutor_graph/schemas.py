"""Structured schemas for the standalone tutor graph bot.

I0.3.1B keeps both classifier and tutor output thin. The small classifier returns
only ``main_type``; the tutor model returns plain student-facing text. Python
derives routing, source flags, safety metadata, and the ``TutorAnswer`` structure.
"""

from __future__ import annotations

from typing import Literal

from pydantic import AliasChoices, BaseModel, Field, computed_field, field_validator


TurnRelation = Literal[
    "student_answer",
    "clarification_choice",
    "new_question",
    "unclear",
]

QuestionMainType = Literal[
    "reference_closed",
    "theory_learning_open",
    "student_answer_to_assess",
    "reaction_illustration_request",
    "experiment_request_caution",
    "calculation_request",
    "off_topic",
    "unclear",
]

SafetyLevel = Literal["safe", "caution", "unsafe"]

TutorRoute = Literal[
    "clarification",
    "reference",
    "theory",
    "diagnostic",
    "student_answer",
    "reaction_illustration",
    "safety_redirect",
    "calculation",
    "off_topic",
]


class ThinQuestionClassification(BaseModel):
    """The entire output contract for the small routing LLM.

    The model does not produce JSON metadata, confidence scores, safety labels,
    source flags, or explanations. It returns one label only.
    """

    main_type: QuestionMainType


class QuestionClassification(BaseModel):
    """Operational classification assembled by Python after the thin label.

    ``needs_course_rag`` and ``needs_user_documents`` are intentionally separate:
    the verified course corpus and user-uploaded AnythingLLM documents are two
    different sources and should not be opened by the same generic flag.
    """

    main_type: QuestionMainType
    turn_relation: TurnRelation | None = Field(
        default=None,
        description=(
            "How the current message relates to the tutor's previous question. "
            "Produced by a separate one-label classifier only when a reply is awaited."
        ),
    )
    needs_course_rag: bool = Field(
        default=False,
        validation_alias=AliasChoices("needs_course_rag", "needs_rag"),
        description="Whether the verified course/local RAG is a candidate source.",
    )
    needs_user_documents: bool = Field(
        default=False,
        description="Whether user-uploaded AnythingLLM documents should be searched.",
    )
    needs_documents_dev: bool = Field(
        default=False,
        description=(
            "Developer override copied into the classification. When true, "
            "needs_user_documents is also true before protected-route policy is applied."
        ),
    )
    needs_wikipedia: bool = False
    needs_diagnostic_question: bool = False
    safety_level: SafetyLevel = "safe"
    reason: str = Field(
        default="derived_by_code",
        min_length=1,
        max_length=500,
        description="Stable operational reason generated by Python, not by the LLM.",
    )

    @field_validator("reason")
    @classmethod
    def normalize_reason(cls, value: str) -> str:
        return " ".join(value.strip().split())

    @computed_field
    @property
    def needs_rag(self) -> bool:
        """Backward-compatible alias for the verified course RAG flag."""
        return self.needs_course_rag

    def short_label(self) -> str:
        return f"{self.main_type} | safety={self.safety_level}"


class RoutingDecision(BaseModel):
    """Deterministic graph route selected from the operational classification."""

    route: TutorRoute
    reason: str = Field(min_length=1, max_length=500)
    classification_main_type: QuestionMainType
    clarification_fallback: bool = False
    safety_override: bool = False

    @field_validator("reason")
    @classmethod
    def normalize_route_reason(cls, value: str) -> str:
        return " ".join(value.strip().split())


class TutorAnswer(BaseModel):
    """Tutor response assembled by Python from plain model text.

    The model is no longer asked to emit this schema. ``tutor_move``, follow-up
    placement, source metadata, and safety notes are assigned programmatically.
    """

    tutor_move: Literal[
        "direct_answer",
        "brief_answer_plus_check",
        "diagnostic_question",
        "clarification_question",
        "feedback_on_student_answer",
        "reaction_illustration",
        "calculation_guidance",
        "safe_redirect",
        "off_topic_redirect",
    ]
    visible_answer: str = Field(min_length=1)
    next_question: str | None = None
    concept_ids: list[str] = Field(default_factory=list, max_length=5)
    safety_note: str | None = None

    def to_cli_text(self) -> str:
        parts = [self.visible_answer.strip()]
        if self.next_question:
            parts.append(self.next_question.strip())
        if self.safety_note:
            parts.append(f"Safety note: {self.safety_note.strip()}")
        return "\n\n".join(part for part in parts if part)
