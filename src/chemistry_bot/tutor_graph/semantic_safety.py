"""Hybrid semantic safety gate for chemistry requests.

The gate combines three inexpensive signals:
1. exact phrase matches;
2. typo-tolerant RapidFuzz matches;
3. cosine similarity against a small set of embedded hazard and procedure prototypes.

The output is an operational signal consumed by Python policy. It is not model
self-confidence and is not generated by the tutor LLM.
"""

from __future__ import annotations

from dataclasses import dataclass, field
import math
import re
import unicodedata
from typing import Any, Literal, Protocol, Sequence

from rapidfuzz import fuzz, process, utils


SafetyDecision = Literal["safe", "caution", "unsafe"]


class EmbeddingProvider(Protocol):
    def embed_query(self, text: str) -> list[float]: ...
    def embed_documents(self, texts: list[str]) -> list[list[float]]: ...


