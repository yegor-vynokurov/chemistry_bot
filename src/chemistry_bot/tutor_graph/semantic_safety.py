@dataclass(frozen=True, slots=True)
class FuzzySignal:
    category: str
    canonical: str
    matched_text: str
    score: float
    method: Literal["exact", "rapidfuzz"]

    def as_dict(self) -> dict[str, Any]:
        return {
            "category": self.category,
            "canonical": self.canonical,
            "matched_text": self.matched_text,
            "score": self.score,
            "method": self.method,
        }


@dataclass(frozen=True, slots=True)
class SemanticMatch:
    category: str | None
    score: float | None
    prototype: str | None

    def as_dict(self) -> dict[str, Any]:
        return {
            "category": self.category,
            "score": self.score,
            "prototype": self.prototype,
        }


@dataclass(frozen=True, slots=True)
class SafetyAssessment:
    decision: SafetyDecision
    normalized_text: str
    embedding_text: str
    hazard_detected: bool
    procedure_detected: bool
    hazard_lexical_score: float | None
    procedure_lexical_score: float | None
    hazard_semantic: SemanticMatch
    procedure_semantic: SemanticMatch
    hazard_matches: tuple[FuzzySignal, ...] = field(default_factory=tuple)
    procedure_matches: tuple[FuzzySignal, ...] = field(default_factory=tuple)
    hazard_threshold: float = 0.60
    procedure_threshold: float = 0.60
    fuzzy_threshold: float = 86.0
    embedding_model_name: str | None = None
    embedding_error: str | None = None
    reason: str = ""

    def as_dict(self) -> dict[str, Any]:
        return {
            "decision": self.decision,
            "normalized_text": self.normalized_text,
            "embedding_text": self.embedding_text,
            "hazard_detected": self.hazard_detected,
            "procedure_detected": self.procedure_detected,
            "hazard_lexical_score": self.hazard_lexical_score,
            "procedure_lexical_score": self.procedure_lexical_score,
            "hazard_semantic": self.hazard_semantic.as_dict(),
            "procedure_semantic": self.procedure_semantic.as_dict(),
            "hazard_matches": [item.as_dict() for item in self.hazard_matches],
            "procedure_matches": [item.as_dict() for item in self.procedure_matches],
            "hazard_threshold": self.hazard_threshold,
            "procedure_threshold": self.procedure_threshold,
            "fuzzy_threshold": self.fuzzy_threshold,
            "embedding_model_name": self.embedding_model_name,
            "embedding_error": self.embedding_error,
            "reason": self.reason,
        }


class LazyOllamaEmbeddingProvider:
    """Load ``OllamaEmbeddings`` only when the first safety check needs it."""

    def __init__(self, model_name: str) -> None:
        self.model_name = model_name
        self._client: Any | None = None

    def _get_client(self) -> Any:
        if self._client is None:
            from langchain_ollama import OllamaEmbeddings

            self._client = OllamaEmbeddings(model=self.model_name)
        return self._client

    def embed_query(self, text: str) -> list[float]:
        return list(self._get_client().embed_query(text))

    def embed_documents(self, texts: list[str]) -> list[list[float]]:
        return [list(item) for item in self._get_client().embed_documents(texts)]


def normalize_safety_text(text: str) -> str:
    normalized = unicodedata.normalize("NFKC", str(text or ""))
    processed = utils.default_process(normalized)
    return " ".join((processed or "").split())


def _phrase_present(text: str, phrase: str) -> bool:
    if not text or not phrase:
        return False
    return re.search(rf"(?<!\w){re.escape(phrase)}(?!\w)", text, flags=re.UNICODE) is not None


def _candidate_spans(text: str, *, max_words: int = 4) -> list[str]:
    words = re.findall(r"\w+", text, flags=re.UNICODE)
    spans: list[str] = []
    for size in range(1, min(max_words, len(words)) + 1):
        spans.extend(" ".join(words[index : index + size]) for index in range(len(words) - size + 1))
    if text and text not in spans:
        spans.append(text)
    return list(dict.fromkeys(spans))


def _collect_lexical_matches(
    text: str,
    aliases: dict[str, tuple[str, ...]],
    *,
    fuzzy_threshold: float,
) -> tuple[FuzzySignal, ...]:
    spans = _candidate_spans(text)
    signals: list[FuzzySignal] = []
    for category, category_aliases in aliases.items():
        best: FuzzySignal | None = None
        for canonical in category_aliases:
            canonical_normalized = normalize_safety_text(canonical)
            if _phrase_present(text, canonical_normalized):
                candidate = FuzzySignal(
                    category=category,
                    canonical=canonical_normalized,
                    matched_text=canonical_normalized,
                    score=100.0,
                    method="exact",
                )
            else:
                canonical_word_count = len(canonical_normalized.split())
                canonical_length = max(1, len(canonical_normalized))
                eligible_spans = []
                for span in spans:
                    span_word_count = len(span.split())
                    length_ratio = min(len(span), canonical_length) / max(len(span), canonical_length)
                    if canonical_word_count == 1:
                        if span_word_count != 1 or length_ratio < 0.65:
                            continue
                    else:
                        if abs(span_word_count - canonical_word_count) > 1 or length_ratio < 0.60:
                            continue
                    eligible_spans.append(span)
                if not eligible_spans:
                    continue
                match = process.extractOne(
                    canonical_normalized,
                    eligible_spans,
                    scorer=fuzz.ratio,
                    processor=None,
                    score_cutoff=fuzzy_threshold,
                )
                if match is None:
                    continue
                matched_text, score, _ = match
                dynamic_cutoff = fuzzy_threshold
                if canonical_word_count == 1:
                    dynamic_cutoff = max(fuzzy_threshold, 90.0)
                if float(score) < dynamic_cutoff:
                    continue
                candidate = FuzzySignal(
                    category=category,
                    canonical=canonical_normalized,
                    matched_text=str(matched_text),
                    score=float(score),
                    method="rapidfuzz",
                )
            if best is None or candidate.score > best.score:
                best = candidate
        if best is not None:
            signals.append(best)
    return tuple(sorted(signals, key=lambda item: item.score, reverse=True))


def _cosine_similarity(left: Sequence[float], right: Sequence[float]) -> float:
    if len(left) != len(right) or not left:
        raise ValueError("Embedding vectors must have the same non-zero length.")
    dot = sum(float(a) * float(b) for a, b in zip(left, right))
    left_norm = math.sqrt(sum(float(value) ** 2 for value in left))
    right_norm = math.sqrt(sum(float(value) ** 2 for value in right))
    if left_norm == 0.0 or right_norm == 0.0:
        return 0.0
    return dot / (left_norm * right_norm)


def _flatten_prototypes(
    prototypes: dict[str, tuple[str, ...]],
) -> tuple[list[str], list[tuple[str, str]]]:
    metadata: list[tuple[str, str]] = []
    texts: list[str] = []
    for category, examples in prototypes.items():
        for example in examples:
            texts.append(example)
            metadata.append((category, example))
    return texts, metadata


class SemanticSafetyGate:
    """Evaluate hazard and procedural intent with reusable embedded prototypes."""

    def __init__(
        self,
        *,
        enabled: bool = True,
        embedding_model_name: str = "nomic-embed-text",
        embedder: EmbeddingProvider | None = None,
        hazard_threshold: float = 0.60,
        procedure_threshold: float = 0.60,
        fuzzy_threshold: float = 86.0,
    ) -> None:
        self.enabled = bool(enabled)
        self.embedding_model_name = embedding_model_name
        self.embedder = embedder or (
            LazyOllamaEmbeddingProvider(embedding_model_name) if self.enabled else None
        )
        self.hazard_threshold = float(hazard_threshold)
        self.procedure_threshold = float(procedure_threshold)
        self.fuzzy_threshold = float(fuzzy_threshold)
        self._hazard_vectors: list[list[float]] | None = None
        self._procedure_vectors: list[list[float]] | None = None
        self._runtime_embedding_error: str | None = None
        self._hazard_texts, self._hazard_metadata = _flatten_prototypes(HAZARD_PROTOTYPES)
        self._procedure_texts, self._procedure_metadata = _flatten_prototypes(PROCEDURE_PROTOTYPES)

    def _ensure_prototype_vectors(self) -> None:
        if self.embedder is None:
            return
        if self._hazard_vectors is None:
            self._hazard_vectors = self.embedder.embed_documents(self._hazard_texts)
        if self._procedure_vectors is None:
            self._procedure_vectors = self.embedder.embed_documents(self._procedure_texts)

    @staticmethod
    def _best_semantic_match(
        query_vector: Sequence[float],
        vectors: Sequence[Sequence[float]],
        metadata: Sequence[tuple[str, str]],
    ) -> SemanticMatch:
        if not vectors:
            return SemanticMatch(category=None, score=None, prototype=None)
        scored = [
            (_cosine_similarity(query_vector, vector), metadata[index])
            for index, vector in enumerate(vectors)
        ]
        score, (category, prototype) = max(scored, key=lambda item: item[0])
        return SemanticMatch(category=category, score=float(score), prototype=prototype)

    def evaluate(self, user_text: str) -> SafetyAssessment:
        normalized = normalize_safety_text(user_text)
        hazard_matches = _collect_lexical_matches(
            normalized,
            HAZARD_ALIASES,
            fuzzy_threshold=self.fuzzy_threshold,
        )
        procedure_matches = _collect_lexical_matches(
            normalized,
            PROCEDURE_ALIASES,
            fuzzy_threshold=self.fuzzy_threshold,
        )
        hazard_lexical_score = hazard_matches[0].score / 100.0 if hazard_matches else None
        procedure_lexical_score = (
            procedure_matches[0].score / 100.0 if procedure_matches else None
        )

        canonical_terms = [item.canonical for item in (*hazard_matches, *procedure_matches)]
        embedding_text = normalized
        if canonical_terms:
            embedding_text += "\ncanonical safety terms: " + "; ".join(canonical_terms)

        hazard_semantic = SemanticMatch(category=None, score=None, prototype=None)
        procedure_semantic = SemanticMatch(category=None, score=None, prototype=None)
        embedding_error: str | None = self._runtime_embedding_error
        if (
            self.enabled
            and self.embedder is not None
            and normalized
            and self._runtime_embedding_error is None
        ):
            try:
                self._ensure_prototype_vectors()
                query_vector = self.embedder.embed_query(embedding_text)
                hazard_semantic = self._best_semantic_match(
                    query_vector,
                    self._hazard_vectors or [],
                    self._hazard_metadata,
                )
                procedure_semantic = self._best_semantic_match(
                    query_vector,
                    self._procedure_vectors or [],
                    self._procedure_metadata,
                )
            except Exception as error:
                embedding_error = str(error)
                self._runtime_embedding_error = embedding_error

        hazard_detected = bool(hazard_matches) or (
            hazard_semantic.score is not None
            and hazard_semantic.score >= self.hazard_threshold
        )
        procedure_detected = bool(procedure_matches) or (
            procedure_semantic.score is not None
            and procedure_semantic.score >= self.procedure_threshold
        )

        if hazard_detected and procedure_detected:
            decision: SafetyDecision = "unsafe"
            reason = "hazard_and_procedural_intent_detected"
        elif hazard_detected:
            decision = "caution"
            reason = "hazard_detected_without_procedural_intent"
        else:
            decision = "safe"
            reason = "no_hazard_above_operational_threshold"

        return SafetyAssessment(
            decision=decision,
            normalized_text=normalized,
            embedding_text=embedding_text,
            hazard_detected=hazard_detected,
            procedure_detected=procedure_detected,
            hazard_lexical_score=hazard_lexical_score,
            procedure_lexical_score=procedure_lexical_score,
            hazard_semantic=hazard_semantic,
            procedure_semantic=procedure_semantic,
            hazard_matches=hazard_matches,
            procedure_matches=procedure_matches,
            hazard_threshold=self.hazard_threshold,
            procedure_threshold=self.procedure_threshold,
            fuzzy_threshold=self.fuzzy_threshold,
            embedding_model_name=self.embedding_model_name if self.enabled else None,
            embedding_error=embedding_error,
            reason=reason,
        )


